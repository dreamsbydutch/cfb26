export function getSeasonHistory(sport: TeamSport, season: number) {
  return history[sport].find((row) => row.season === season)
}

export function getSeasonCoach(sport: TeamSport, season: number) {
  const completed = getSeasonHistory(sport, season)
  if (completed)
    return { name: completed.coach, sourceUrl: seasonHistorySources[sport] }
  // Verified against the explicit 2026–27 staff pages, not the prior season's staff.
  if (season !== 2026) return undefined
  return sport === 'basketball'
    ? {
        name: 'Mike Boynton Jr.',
        sourceUrl: 'https://mgoblue.com/sports/mens-basketball/coaches/2026-27',
      }
    : {
        name: 'Brandon Naurato',
        sourceUrl: 'https://mgoblue.com/sports/mens-ice-hockey/coaches/2026-27',
      }
}
