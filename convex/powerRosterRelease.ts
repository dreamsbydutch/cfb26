/** Reuse the newest past-only fit until the next annual evaluation approves a refit. */
export function releasedRosterFit(season: number): RosterFit | undefined {
  const latest = Math.max(
    ...Object.keys(POWER_ROSTER_FITS)
      .map(Number)
      .filter((year) => year <= season),
  )
  return POWER_ROSTER_FITS[latest]
}
